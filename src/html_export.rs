#[cfg(test)]
mod tests {
    use super::*;
    use crate::parser::types::{
        BcftoolsStats, BcftoolsSummary, FastqcBasicStats, FastqcReport, SamtoolsStats,
        SamtoolsSummary, TsTvStats,
    };
    use std::path::PathBuf;

    #[test]
    fn test_html_escape() {
        assert_eq!(html_escape("a<b>&\"c'd"), "a&lt;b&gt;&amp;&quot;c&#39;d");
        assert_eq!(html_escape("plain"), "plain");
    }

    fn results_with(samtools_count: usize) -> QcResults {
        let samtools: Vec<SamtoolsStats> = (0..samtools_count)
            .map(|i| SamtoolsStats {
                source_file: PathBuf::from(format!("/data/sample{}.stats", i)),
                summary: SamtoolsSummary {
                    raw_total_sequences: 1000,
                    reads_mapped: if i == 0 { 600 } else { 950 },
                    reads_duplicated: 50,
                    error_rate: 0.001,
                    average_quality: 30.0,
                    ..Default::default()
                },
                coverage_histogram: vec![],
                insert_size_histogram: vec![],
                read_length_histogram: vec![],
                gc_content_first: vec![],
                gc_content_last: vec![],
            })
            .collect();
        QcResults {
            scan_path: PathBuf::from("/test"),
            samtools_reports: samtools,
            bcftools_reports: vec![BcftoolsStats {
                source_file: PathBuf::from("/data/v.vcf.stats"),
                summary: BcftoolsSummary {
                    num_records: 100,
                    num_snps: 80,
                    num_indels: 20,
                    ..Default::default()
                },
                tstv: TsTvStats {
                    ts: 60,
                    tv: 30,
                    ts_tv_ratio: 2.0,
                    ..Default::default()
                },
                substitution_types: vec![],
                allele_freq: vec![],
                qual_dist: vec![],
                indel_dist: vec![],
                depth_dist: vec![],
            }],
            fastqc_reports: vec![FastqcReport {
                source_file: PathBuf::from("/data/s_fastqc.zip"),
                sample_name: "s".into(),
                basic_statistics: FastqcBasicStats {
                    total_sequences: 100,
                    percent_gc: 45.0,
                    ..Default::default()
                },
                per_base_quality: vec![],
                per_sequence_quality: vec![],
                per_base_gc_content: vec![],
                per_sequence_gc_content: vec![],
                sequence_length_dist: vec![],
                overrepresented_sequences: vec![],
                module_statuses: vec![],
            }],
        }
    }

    #[test]
    fn test_html_contains_sections() {
        let results = results_with(6);
        let thresholds = ThresholdConfig::default();
        let tmp = std::env::temp_dir().join("qcforge_test_html_sections.html");
        write_html(&tmp, &results, &thresholds, None, None).unwrap();
        let content = std::fs::read_to_string(&tmp).unwrap();
        assert!(content.contains("<title>QCForge report"));
        assert!(content.contains("id=\"summary\""));
        assert!(content.contains("id=\"cohort\""));
        assert!(content.contains("id=\"samtools\""));
        assert!(content.contains("id=\"bcftools\""));
        assert!(content.contains("id=\"fastqc\""));
        // sample0 has 60% mapping → should be flagged QC FAIL somewhere
        assert!(content.contains("qc-fail"));
        std::fs::remove_file(&tmp).ok();
    }

    #[test]
    fn test_html_contains_boxplot_svg() {
        let results = results_with(6);
        let thresholds = ThresholdConfig::default();
        let tmp = std::env::temp_dir().join("qcforge_test_html_svg.html");
        write_html(&tmp, &results, &thresholds, None, None).unwrap();
        let content = std::fs::read_to_string(&tmp).unwrap();
        assert!(content.contains("<svg"));
        assert!(content.contains("class=\"box\""));
        assert!(content.contains("class=\"median\""));
        std::fs::remove_file(&tmp).ok();
    }

    #[test]
    fn test_html_too_small_cohort() {
        // Only 3 samtools samples → all metrics too small for IQR.
        let results = results_with(3);
        let thresholds = ThresholdConfig::default();
        let tmp = std::env::temp_dir().join("qcforge_test_html_small.html");
        write_html(&tmp, &results, &thresholds, None, None).unwrap();
        let content = std::fs::read_to_string(&tmp).unwrap();
        assert!(content.contains("Cohort analysis requires"));
        // Summary section still renders
        assert!(content.contains("id=\"summary\""));
        std::fs::remove_file(&tmp).ok();
    }
}
